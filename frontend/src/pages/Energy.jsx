import { BarList, LineChart } from '../components/Charts'
import SimBadge from '../components/SimBadge'
import { COLORS, round1, sum, weekLabels } from '../utils/helpers'

export default function Energy({ apartments }) {
  const labels = weekLabels()
  const series = apartments.map((a, i) => ({
    label: a.name, color: COLORS[i % COLORS.length], values: [...a.energyHistory, round1(a.energyToday)],
  }))
  const weekTotals = apartments.map((a, i) => ({
    label: `${a.name} (${a.city})`, value: round1(sum(a.energyHistory) + a.energyToday), color: COLORS[i % COLORS.length],
  }))
  const total = round1(sum(weekTotals.map((w) => w.value)))
  const top = [...weekTotals].sort((a, b) => b.value - a.value)[0]
  const today = round1(sum(apartments.map((a) => a.energyToday)))
  const avg = round1(total / 7)

  return (
    <div className="page">
      <div className="kpis">
        <div className="kpi"><div><b>{today}</b><small>kWh today (all apartments)</small></div></div>
        <div className="kpi"><div><b>{total}</b><small>kWh over 7 days</small></div></div>
        <div className="kpi"><div><b>{avg}</b><small>kWh / day average</small></div></div>
        <div className="kpi kpi-warn"><div><b>{top.label.split(' (')[0]}</b><small>Highest consumer</small></div></div>
      </div>

      <section className="card">
        <div className="card-head"><h3>Daily consumption per apartment</h3><SimBadge text="Simulated kWh" /></div>
        <LineChart labels={labels} series={series} />
        <div className="legend">
          {series.map((s) => <span key={s.label}><i style={{ background: s.color }} />{s.label}</span>)}
        </div>
      </section>

      <section className="grid-2">
        <div className="card">
          <div className="card-head"><h3>Comparison — last 7 days</h3><SimBadge /></div>
          <BarList items={weekTotals} />
        </div>
        <div className="card">
          <div className="card-head"><h3>Details</h3></div>
          <table className="table">
            <thead><tr><th>Apartment</th><th>City</th><th>Today</th><th>7 days</th></tr></thead>
            <tbody>
              {apartments.map((a, i) => (
                <tr key={a.id}>
                  <td>{a.name}</td><td>{a.city}</td>
                  <td>{a.energyToday.toFixed(2)} kWh</td><td>{weekTotals[i].value} kWh</td>
                </tr>
              ))}
            </tbody>
          </table>
          <p className="muted">All figures are generated by the IoT simulation. They do not come from real electricity meters.</p>
        </div>
      </section>
    </div>
  )
}
